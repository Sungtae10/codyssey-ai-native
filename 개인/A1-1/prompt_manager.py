# ============================================================
# 메뉴와 프로그램 시작점
# ============================================================
def show_menu():
    """메인 메뉴를 출력한다."""
    print()
    print("=== 나만의 프롬프트 관리 ===")
    print("1. 프롬프트 추가")
    print("2. 프롬프트 목록")
    print("3. 카테고리별 조회")
    print("4. 프롬프트 검색")
    print("5. 프롬프트 상세 보기")
    print("6. 즐겨찾기 관리")
    print("7. 즐겨찾기 목록")
    print("0. 종료")


def main():
    """프로그램 시작점. 사용자가 0을 입력할 때까지 메뉴를 반복해서 보여 준다."""
    while True:
        show_menu()
        choice = input("선택: ").strip()

        if choice in ("1", "2", "3", "4", "5", "6", "7"):
            print("아직 준비 중인 기능입니다.")
        elif choice == "0":
            print("\n프로그램을 종료합니다. 실행 중에 추가하거나 바꾼 내용은 초기화됩니다.")
            break
        else:
            print("잘못된 입력입니다. 메뉴에 있는 번호를 입력해 주세요.")


if __name__ == "__main__":
    main()
